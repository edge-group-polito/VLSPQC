# Places a hand-driveable main.c + include/test_vectors_<suffix>.h directly
# in each FAEST variant dir, matching the original/DS/FALCON/<variant>/main.c
# convention (TEST_KEY/TEST_SIGN/TEST_SIGN_OPEN flags, embedded KAT vectors,
# no file I/O) -- as opposed to the dynamic kat/gen/main_faest.c flow (which
# fopen()s a .rsp at runtime) or the on-demand `make static-test-*` flow
# (which regenerates a throwaway folder under kat/static/).
#
# The content is generated by the same static-test renderer used by
# `make static-test-<variant>` (tools/gen_static_test.py, ds_drbg_hawk
# shape -- already validated against real KAT data), then copied in place
# and its RUN_KEYGEN/RUN_SIGN/RUN_VERIFY flags renamed to
# TEST_KEY/TEST_SIGN/TEST_SIGN_OPEN to match FALCON's naming.
#
# Run from pqrv/ after tools/assemble_faest.sh:
#   tools/build_faest_main.sh
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd "$SCRIPT_DIR/.." && pwd)
FAEST_DIR="$ROOT/original/Additional-DS/FAEST"
STATIC_DIR="$ROOT/kat/static"

VARIANTS=(
  FAEST_128F FAEST_128S FAEST_192F FAEST_192S FAEST_256F FAEST_256S
  FAEST_EM_128F FAEST_EM_128S FAEST_EM_192F FAEST_EM_192S FAEST_EM_256F FAEST_EM_256S
)

for NAME in "${VARIANTS[@]}"; do
  suffix=${NAME#FAEST_}
  vdir="$FAEST_DIR/$NAME"
  out_static="$STATIC_DIR/$NAME"

  rm -rf "$out_static"
  make -C "$ROOT" "static-test-$NAME" STATIC_KATNUM=1 >/dev/null

  cp "$out_static/test_vectors_$suffix.h" "$vdir/include/"

  cat <<EOF > "$vdir/main.c"
///////////////////////////////////////////////////////////////////////////////////////
// Entry point for testing the FAEST implementation ($NAME) using an input/output
// test vector generated from the NIST-framework AES-256-CTR DRBG, same convention
// as original/DS/FALCON/*/main.c. Body generated by tools/gen_static_test.py from
// real KAT data (see tools/build_faest_main.sh); flags renamed to match FALCON's
// TEST_KEY/TEST_SIGN/TEST_SIGN_OPEN convention.
///////////////////////////////////////////////////////////////////////////////////////
EOF
  # Strip upstream's own auto-generated banner (everything up to and
  # including the second "////...////" divider -- found dynamically since
  # different shapes' banners aren't all the same length) before appending
  # its body, renamed.
  awk '/^\/+$/ { n++; if (n == 2) { found = 1; next } } found' "$out_static/main.c" | sed \
    -e 's/RUN_KEYGEN/TEST_KEY/g' \
    -e 's/RUN_SIGN\b/TEST_SIGN/g' \
    -e 's/RUN_VERIFY/TEST_SIGN_OPEN/g' \
    >> "$vdir/main.c"

  rm -rf "$out_static"
  echo "built $NAME/main.c + $NAME/include/test_vectors_$suffix.h"
done

# Places a hand-driveable main.c + include/test_vectors_<suffix>.h directly
# in each SNOVA variant dir, matching the algorithms/signatures/standard/FALCON/<variant>/main.c
# convention (TEST_KEY/TEST_SIGN/TEST_SIGN_OPEN flags, embedded KAT vectors,
# no file I/O) -- as opposed to the dynamic harness/gen/main_snova.c flow (which
# fopen()s a .rsp at runtime) or the on-demand `make static-test-*` flow
# (which regenerates a throwaway folder under vectors/static/). Same recipe as
# tools/build_faest_main.sh / tools/build_uov_main.sh / tools/build_mayo_main.sh /
# tools/build_qruov_main.sh.
#
# The content is generated by the same static-test renderer used by
# `make static-test-<variant>` (tools/gen_static_test.py, ds_drbg_hawk
# shape -- already validated against real KAT data), then copied in place
# and its RUN_KEYGEN/RUN_SIGN/RUN_VERIFY flags renamed to
# TEST_KEY/TEST_SIGN/TEST_SIGN_OPEN to match FALCON's naming.
#
# The 8 largest variants (level-5 tier, see the family's own README.md)
# need `ulimit -s 65536` before running `make static-test-*` for them --
# the Makefile's own gen-*/test-* recipes already set this, but this
# script's `make -C "$ROOT" static-test-$NAME` call is a fresh subshell.
#
# Run from pqrv/:
#   tools/build_snova_main.sh
set -euo pipefail

ulimit -s 65536 2>/dev/null || true

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd "$SCRIPT_DIR/.." && pwd)
SNOVA_DIR="$ROOT/algorithms/signatures/onramp/SNOVA"
STATIC_DIR="$ROOT/vectors/static"

VARIANTS=(
  SNOVA_28_5_19_4_AES SNOVA_28_5_19_4
  SNOVA_24_5_16_4_AES SNOVA_24_5_16_4
  SNOVA_48_17_16_2_AES SNOVA_48_17_16_2
  SNOVA_48_16_19_2_AES SNOVA_48_16_19_2
  SNOVA_28_4_16_4x5_AES SNOVA_28_4_16_4x5
  SNOVA_28_4_19_4x5_AES SNOVA_28_4_19_4x5
  SNOVA_40_7_19_4_AES SNOVA_40_7_19_4
  SNOVA_37_8_16_4_AES SNOVA_37_8_16_4
  SNOVA_72_25_16_2_AES SNOVA_72_25_16_2
  SNOVA_72_24_19_2_AES SNOVA_72_24_19_2
  SNOVA_38_5_16_4x5_AES SNOVA_38_5_16_4x5
  SNOVA_38_5_19_4x5_AES SNOVA_38_5_19_4x5
  SNOVA_50_9_19_4_AES SNOVA_50_9_19_4
  SNOVA_60_10_16_4_AES SNOVA_60_10_16_4
  SNOVA_97_33_16_2_AES SNOVA_97_33_16_2
  SNOVA_96_32_19_2_AES SNOVA_96_32_19_2
  SNOVA_52_6_16_4x6_AES SNOVA_52_6_16_4x6
  SNOVA_52_6_19_4x6_AES SNOVA_52_6_19_4x6
)

for NAME in "${VARIANTS[@]}"; do
  suffix=${NAME#SNOVA_}
  vdir="$SNOVA_DIR/$NAME"
  out_static="$STATIC_DIR/$NAME"

  rm -rf "$out_static"
  make -C "$ROOT" "static-test-$NAME" STATIC_KATNUM=1 >/dev/null

  cp "$out_static/test_vectors_$suffix.h" "$vdir/include/"

  cat <<EOF > "$vdir/main.c"
///////////////////////////////////////////////////////////////////////////////////////
// Entry point for testing the SNOVA implementation ($NAME) using an input/output
// test vector generated from the NIST-framework AES-256-CTR DRBG, same convention
// as algorithms/signatures/standard/FALCON/*/main.c. Body generated by tools/gen_static_test.py from
// real KAT data (see tools/build_snova_main.sh); flags renamed to match FALCON's
// TEST_KEY/TEST_SIGN/TEST_SIGN_OPEN convention.
///////////////////////////////////////////////////////////////////////////////////////
EOF
  # Strip upstream's own auto-generated banner (10 lines, ending at the
  # second "////...////" divider) before appending its body, renamed.
  tail -n +11 "$out_static/main.c" | sed \
    -e 's/RUN_KEYGEN/TEST_KEY/g' \
    -e 's/RUN_SIGN\b/TEST_SIGN/g' \
    -e 's/RUN_VERIFY/TEST_SIGN_OPEN/g' \
    >> "$vdir/main.c"

  rm -rf "$out_static"
  echo "built $NAME/main.c + $NAME/include/test_vectors_$suffix.h"
done

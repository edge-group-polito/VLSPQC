# Places a hand-driveable main.c + include/test_vectors_<suffix>.h directly
# in each SQISIGN variant dir, matching the algorithms/signatures/standard/FALCON/<variant>/main.c
# convention (TEST_KEY/TEST_SIGN/TEST_SIGN_OPEN flags, embedded KAT vectors,
# no file I/O) -- as opposed to the dynamic harness/gen/main_sqisign.c flow (which
# fopen()s a .rsp at runtime) or the on-demand `make static-test-*` flow
# (which regenerates a throwaway folder under vectors/static/). Same recipe as
# tools/build_mayo_main.sh / tools/build_uov_main.sh (common/ + per-variant
# split); unlike MAYO, SQIsign's api.h uses `unsigned long long` for
# smlen/mlen (matching HAWK), so no smlen/mlen1 type rewrite is needed here.
#
# Run from VLSPQC/:
#   tools/build_sqisign_main.sh
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd "$SCRIPT_DIR/.." && pwd)
SQISIGN_DIR="$ROOT/algorithms/signatures/onramp/SQISIGN"
STATIC_DIR="$ROOT/vectors/static"

VARIANTS=(sqisign_lvl1 sqisign_lvl3 sqisign_lvl5)

for NAME in "${VARIANTS[@]}"; do
  vdir="$SQISIGN_DIR/$NAME"
  out_static="$STATIC_DIR/$NAME"

  rm -rf "$out_static"
  make -C "$ROOT" "static-test-$NAME" STATIC_KATNUM=1 >/dev/null

  cp "$out_static/test_vectors_$NAME.h" "$vdir/include/"

  cat <<EOF > "$vdir/main.c"
///////////////////////////////////////////////////////////////////////////////////////
// Entry point for testing the SQIsign implementation ($NAME) using an input/output
// test vector generated from the NIST-framework AES-256-CTR DRBG, same convention
// as algorithms/signatures/standard/FALCON/*/main.c. Body generated by tools/gen_static_test.py from
// real KAT data (see tools/build_sqisign_main.sh); flags renamed to match FALCON's
// TEST_KEY/TEST_SIGN/TEST_SIGN_OPEN convention.
///////////////////////////////////////////////////////////////////////////////////////
EOF
  # Strip upstream's own auto-generated banner (10 lines, ending at the
  # second "////...////" divider) before appending its body, renamed.
  tail -n +11 "$out_static/main.c" | sed \
    -e 's/RUN_KEYGEN/TEST_KEY/g' \
    -e 's/RUN_SIGN\b/TEST_SIGN/g' \
    -e 's/RUN_VERIFY/TEST_SIGN_OPEN/g' \
    >> "$vdir/main.c"

  rm -rf "$out_static"
  echo "built $NAME/main.c + $NAME/include/test_vectors_$NAME.h"
done
